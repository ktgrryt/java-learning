#!/usr/bin/env bash
#
# docs/guide.md に書いた集計が、いまの教材と合っているかを検査する。
#
#   ./tools/check-guide-numbers.sh          … 検査する
#   ./tools/check-guide-numbers.sh --list   … content/ から数え直した値を全部出す
#
# ガイドは「★の総数」「必須問題数」「テストケース件数」「single-fileの問題数」のような数を
# 根拠として書いている。ところがこれは**教材を増やすたびに必ず古くなる**。実際に一度の
# レビューで6箇所ずれていた（★678→680、必須662→664、single-file 579→613、到達目標282→283、
# 非single-fileを含む章の一覧が11章漏れ、rubricの内訳の合計が本文と不一致）。
# どれも読み手が判断の根拠にする数なので、古いまま残ると見積りが狂う。
#
# 人手のレビューでは気づけないものは機械で数える ― クイズの手がかり、章参照の番号、
# 省略されたキーと同じ扱いをガイドの数にも与える。
#
# 数え方は `jq.content.Task` / `Lesson` の公開表現（`/api/state`）に合わせてあるので、
# `verify-solutions.sh` が最後に出す集計と同じ値になる。サーバーもJDKも使わないので1秒で終わる。
#
# **文を書き換えたときは、この検査の正規表現も直すこと。** 合致しなくなったら
# 「該当する記述が見つかりません」として失敗する（黙って検査対象から外れないように）。
set -euo pipefail

cd "$(dirname "$0")/.."

python3 -u tools/check_guide_numbers.py "$@"
