#!/usr/bin/env bash
#
# 配色（web/style.css の2枚のパレット）の読みやすさを確かめる。
#
#   ./tools/check-contrast.sh          … 検査する
#   ./tools/check-contrast.sh --list   … 全組み合わせの実測値を出す
#
# 配色は「暗い」「明るい」の2枚あり、同じ変数名で色だけが入れ替わる。**片方だけを見て
# 決めると、もう片方で字が沈む。** 明るい配色の主ボタンが濃い茶に黒い字で 4.92:1、
# アクセントを字の色に使った箇所が 3.28:1 だったのがそれで、どちらも指摘されて気づいた
# （2026-08-23）。色を1つ動かすたびに関わる組み合わせを数え直す必要があるので、
# ここで機械に数えさせる。
#
# サーバーもJDKも使わないので1秒で終わる。web/style.css のパレットを触ったら通すこと。
set -euo pipefail

cd "$(dirname "$0")/.."

python3 -u tools/check_contrast.py "$@"
