#!/usr/bin/env bash
#
# 期待出力が1種類しかない問題を数える（写すだけで通る問題を防ぐ）。
#
#   ./tools/check-constant-output.sh          … 検査する
#   ./tools/check-constant-output.sh --list   … 該当する問題を全部出す
#
# テストケースの期待出力が全部同じなら、その文字列を `println` で出すだけで合格する。
# 表示ケースには期待出力が見えているので、写せば通る。**採点が何も測っていない状態**になる。
# 実際に `27-2#2`（トランザクションの内と外を分ける問題）が、入力なし・ケース1件・検査なしで、
# 模範解答が `println` 4行だった（レビュー08-16で発見。入力で出力が変わる形へ作り直した）。
#
#   失敗 … 出力が1種類 かつ `sourceChecks` が無い（`ch01`〜`ch03` は目標上やむを得ないので除く）
#   参考 … 出力が1種類だが `sourceChecks` がある（検査だけが防波堤なので件数を出す）
#
# サーバーもJDKも使わないので1秒で終わる。問題を足したりケースを削ったら通すこと。
set -euo pipefail

cd "$(dirname "$0")/.."

python3 -u tools/check_constant_output.py "$@"
