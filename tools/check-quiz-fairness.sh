#!/usr/bin/env bash
#
# 確認クイズに「Javaを知らなくても解ける手がかり」が無いかを検査する。
#
#   ./tools/check-quiz-fairness.sh          … 検査する
#   ./tools/check-quiz-fairness.sh --list   … 基準を外れている問題を全部出す
#
# 4択で正解を当てられてしまう手がかりは、Javaの理解とは無関係に正答率を上げる。過去に3つ潰したが、
# クイズが391問へ増える過程で2つが戻っていた。人手のレビューでは気づけなかったので機械で数える。
#
#   1. 正解が目に見えて長い（8字以上）… 長いほうを選ぶだけで当たる
#   2. 断定語（必ず・常に・すべて・絶対）が誤答にだけ出る … 断定を避けるだけで当たる
#
# どちらも「誤答を具体化する」ことで同時に直る。投げやりな一言の誤答をやめると、長さも断定語も
# 自然にそろう。
#
# 正解の位置の偏りは表示するが失敗にはしない。並べ替えると `progress.json` の `quizChoices`
# （学習者が選んだ番号）の意味が変わり、正解した記録が誤答になってしまうため直せない。
#
# サーバーもJDKも使わないので1秒で終わる。クイズを足したり選択肢を書き換えたら通すこと。
set -euo pipefail

cd "$(dirname "$0")/.."

python3 -u tools/check_quiz_fairness.py "$@"
