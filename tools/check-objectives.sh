#!/usr/bin/env bash
#
# 章の到達目標（objectives）と、問題・クイズへの紐づけを検査する。
#
#   ./tools/check-objectives.sh              … 検査する（全69章に到達目標が必要）
#   ./tools/check-objectives.sh --list       … 章ごとの記述状況を一覧する
#   ./tools/check-objectives.sh --baseline 3 … 未記述を許す章数を一時的に緩める
#
# 章クリアは「必須問題を全部解いたか」、`layers` は「概念・コード・実践のどこまで到達したか」を
# 答える。どちらも**終わったか**の話で、**何ができるようになるか**は構造化されていなかった。
# `objectives` はそこを埋めるが、宣言しただけでは実態とずれるので次を見張る。
#
#   宣言した目標は、必ずその章の問題かクイズで測られていること
#   問題とクイズは、必ずどれかの目標へ紐づいていること
#   目標は「〜できる」の形で、観察できる状態を書いていること
#
# `objectiveIds` はレッスンに書き、問題は必要なときだけ上書きする。レッスン内の問題は同じ目標を
# 測ることが多いので、全問へ書かせると重複が増えて実態と合わなくなるほうが早い。
#
# 全69章へ書き終えたので、既定では未記述を1章も許さない。章を足すときは目標も書くこと。
#
# サーバーもJDKも使わないので1秒で終わる。到達目標を足したり紐づけを変えたら通すこと。
set -euo pipefail

cd "$(dirname "$0")/.."

python3 -u tools/check_objectives.py "$@"
